#!/usr/bin/env bash
# Brings Sage's face, mood and patience from destbreso.com's own code into design/site/sage-site.js, so the desk
# draws the same Sage the site does and never a copy kept by hand. SAGE_SITE is the path to the site's checkout on
# this machine; nothing else names it.
set -euo pipefail
: "${SAGE_SITE:?set SAGE_SITE to the path of the checkout of destbreso.com}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/design/site/sage-site.js"
ESBUILD="$SAGE_SITE/node_modules/.bin/esbuild"
[ -x "$ESBUILD" ] || ESBUILD="npx --yes esbuild@0.24.2"
ENTRY="$(mktemp -t sage-site).ts"
cat > "$ENTRY" <<TS
export { drawSageFace, drawSageHead, SAGE_GREEN, SAGE_BOX } from "$SAGE_SITE/components/room/sage-face";
export { stepMood, CROSS_ANSWER } from "$SAGE_SITE/components/room/sage-mood";
export { PATIENCE, newPatience, stepPatience, outOfPatience, asked } from "$SAGE_SITE/components/room/patience";
TS
TMP="$(mktemp -t sage-site).js"
$ESBUILD "$ENTRY" --bundle --format=iife --global-name=SageSite --target=es2020 --log-level=warning --outfile="$TMP"
{
  echo "// Generated by tools/sync-site.sh from destbreso.com's own code: Sage's face, mood and patience."
  echo "// Do not edit. Change it on the site and run the script again. Part of Sage's art: see LICENSE-ART.md."
  # (the bundler names each source file in a comment: those lines are left out)
  grep -v '^ *// .*\.ts$' "$TMP"
} > "$OUT"
rm -f "$ENTRY" "$TMP"
echo "wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
